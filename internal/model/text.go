package model

// InvisibleRune — невидимые символы форматирования: управление
// направлением текста (U+202A–U+202E, U+2066–U+2069, U+200E, U+200F,
// U+061C) и символы нулевой ширины (U+200B–U+200D, U+2060–U+2064,
// U+FEFF). Имя и командную строку задаёт сам процесс: с U+202E
// («справа налево») строка в панели выглядит иначе, чем выполняется, а
// символ нулевой ширины делает «sshd» и «ss​hd» неразличимыми.
func InvisibleRune(r rune) bool {
	switch {
	case r >= 0x200B && r <= 0x200F, r >= 0x202A && r <= 0x202E,
		r >= 0x2060 && r <= 0x2064, r >= 0x2066 && r <= 0x2069,
		r == 0xFEFF, r == 0x061C:
		return true
	}
	return false
}
